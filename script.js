const pageTitles = {
  en: {
    home: "Qiya Support",
    privacy: "Privacy Policy · Qiya Support",
    terms: "Terms of Service · Qiya Support"
  },
  zh: {
    home: "Qiya 支持",
    privacy: "隐私政策 · Qiya 支持",
    terms: "服务条款 · Qiya 支持"
  }
};

const html = document.documentElement;
const page = document.body.dataset.page || "home";
const languageButtons = document.querySelectorAll("[data-language]");
const translatableNodes = document.querySelectorAll("[data-i18n]");
const ariaNodes = document.querySelectorAll("[data-i18n-aria]");
const englishText = new Map(Array.from(translatableNodes, (node) => [node, node.innerHTML]));
const englishAria = new Map(Array.from(ariaNodes, (node) => [node, node.getAttribute("aria-label")]));

function setLanguage(language) {
  const selected = language === "zh" ? "zh" : "en";
  const dictionary = translations[selected] || {};
  html.lang = selected === "zh" ? "zh-Hans" : "en";
  document.title = pageTitles[selected][page];

  translatableNodes.forEach((node) => {
    const key = node.dataset.i18n;
    node.innerHTML = selected === "en" ? englishText.get(node) : (dictionary[key] ?? englishText.get(node));
  });

  ariaNodes.forEach((node) => {
    const key = node.dataset.i18nAria;
    node.setAttribute("aria-label", selected === "en" ? englishAria.get(node) : (dictionary[key] ?? englishAria.get(node)));
  });

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === selected));
  });

  try {
    localStorage.setItem("qiya-support-language", selected);
  } catch (_) {
    // The site remains usable when local storage is unavailable.
  }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

let savedLanguage = "en";
try {
  savedLanguage = localStorage.getItem("qiya-support-language") || "en";
} catch (_) {
  savedLanguage = "en";
}

setLanguage(savedLanguage);
document.querySelectorAll("#year").forEach((node) => {
  node.textContent = String(new Date().getFullYear());
});
